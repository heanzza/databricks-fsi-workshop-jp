# MAGIC # 📊 Tableau との比較
# MAGIC
# MAGIC お客様の多くが Tableau をご利用のため、AI/BI Dashboard との違いを整理します。
# MAGIC **「BI単体ツール」なのか「データ基盤と一体化したBI」なのか**が最大の違いです。
# MAGIC
# MAGIC | 観点 | **Databricks AI/BI Dashboard** | **Tableau** |
# MAGIC |------|------------------------------|-------------|
# MAGIC | 位置づけ | データ基盤（Lakehouse）と**一体** | 独立したBI専用ツール（別途接続） |
# MAGIC | データ接続 | 同一プラットフォーム上のテーブルを直接参照（**抽出/Extract不要**） | データソースへ接続・抽出（Extract）を管理 |
# MAGIC | 自然言語 | **標準搭載**（日本語でグラフ生成・Q&A＝Genie） | 生成AI機能は限定的／別ライセンス |
# MAGIC | ガバナンス | **Unity Catalog の権限がそのまま効く**（行フィルタ・列マスキングもBIに反映） | ツール側で別途権限設計が必要 |
# MAGIC | リネージ／監査 | データ→ダッシュボードまで**一元で追跡** | ツール外のデータ来歴は別管理 |
# MAGIC | 鮮度 | ライブ接続でニアリアルタイム | 抽出のスケジュール管理が必要 |
# MAGIC | 対話的深掘り | 閲覧者が**その場で日本語質問**（Genie） | 事前定義のフィルタ・アクション中心 |
# MAGIC | 学習コスト | SQL/自然言語。ビジネス職も可 | 専用の操作習得が必要 |
# MAGIC
# MAGIC ### 🗣️ 商談での一言
# MAGIC > 「Tableau は"BIツール"、AI/BI Dashboard は"**データ基盤と一体化したBI**"。
# MAGIC > 取込〜ガバナンス〜AI（Genie）〜可視化が**同じ基盤・同じ権限**で完結するので、
# MAGIC > `06` で設定する**行レベル権限や電話番号マスキングが、そのままダッシュボードにも効きます**。」
# MAGIC
# MAGIC > 💡 **共存も可能**: 既存の Tableau は Databricks SQL に接続してそのまま利用できます。
